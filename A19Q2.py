

Multiplication = lambda No1 ,No2 : No1* No2

def main():

    Num1 = int(input("Enter Number1: "))
    Num2 = int(input("Enter Number2: "))

    Ret = Multiplication(Num1, Num2)
    print(f"Multiplication of {Num1} and {Num2} is {Ret}")
              
if __name__=="__main__":
    main()
